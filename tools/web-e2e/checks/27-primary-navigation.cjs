// Main destinations, existing tools, navigation while a draft or approval is open, and phone layouts.
const path = require('path')
const { WEB, SHOTS, check } = require('../lib.cjs')

module.exports = async ({ browser }) => {
  const page = await browser.newPage({ viewport: { width: 360, height: 800 }, locale: 'en-US' })
  try {
    await page.goto(WEB + '/')
    const nav = page.getByRole('navigation', { name: 'Main navigation' })
    const go = name => nav.getByRole('button', { name, exact: true }).click()
    const back = () => page.evaluate(() => window.hermesBack())
    const draft = page.getByPlaceholder('Message Hermes')
    await draft.waitFor()
    await page.getByRole('button', { name: 'Add', exact: true }).waitFor()
    await page.waitForFunction(() => !document.querySelector('.conn-banner'))
    await draft.fill('مسودة تبقى في نفس المحادثة')
    await go('Home')
    const home = page.getByRole('region', { name: 'Home', exact: true })
    await home.getByRole('status').waitFor()
    check((await home.getByRole('status').innerText()).startsWith('Connected'), 'Home reflects the existing gateway connection')
    await home.getByRole('button', { name: 'Status details' }).click()
    const status = page.locator('.sheet', { hasText: 'Backend status' })
    await status.waitFor()
    await status.getByRole('button', { name: 'Setup check' }).click()
    await page.getByText('Setup check', { exact: true }).first().waitFor()
    await back()
    await home.waitFor()
    await page.screenshot({ path: path.join(SHOTS, 'hermes-phase-01-home-dark.png') })

    await go('Work')
    const work = page.getByRole('region', { name: 'Work', exact: true })
    check(!/CAD|DWG|DXF/i.test(await work.innerText()), 'Work contains only the remaining tools')
    await work.getByRole('button', { name: /Files/ }).click()
    await page.locator('.screen .topbar').getByText('Files', { exact: true }).waitFor()
    await back()
    await work.waitFor()

    await go('Knowledge')
    const knowledge = page.getByRole('region', { name: 'Knowledge', exact: true })
    await knowledge.getByRole('button', { name: /Model providers/ }).click()
    await page.locator('.screen .topbar').getByText('Model providers', { exact: true }).waitFor()
    await back()
    await knowledge.getByRole('button', { name: /Default models/ }).click()
    await page.locator('.screen .topbar').getByText('Default models', { exact: true }).waitFor()
    await back()
    await knowledge.waitFor()
    check(true, 'direct provider and model pages return to Knowledge')

    await go('More')
    const more = page.getByRole('region', { name: 'More', exact: true })
    await more.getByRole('button', { name: /Settings/ }).click()
    await page.locator('.screen .topbar').getByText('Settings', { exact: true }).waitFor()
    await back()
    await more.waitFor()
    await go('Conversations')
    const sessions = page.getByRole('main', { name: 'Conversations' })
    await sessions.getByRole('searchbox').waitFor()
    await back()
    await home.getByRole('button', { name: 'Continue chat' }).click()
    check(await draft.inputValue() === 'مسودة تبقى في نفس المحادثة', 'navigating between destinations preserves the draft and chat')
    await page.screenshot({ path: path.join(SHOTS, 'hermes-phase-01-chat.png') })
    await page.getByRole('button', { name: 'Add', exact: true }).click()
    const add = page.locator('.picker-backdrop')
    await add.getByText('File', { exact: true }).waitFor()
    check(!/CAD|DWG|DXF/i.test(await add.innerText()), 'the composer keeps the normal file picker without CAD options')
    await back()
    await go('Work')
    await page.evaluate(() => window.hermesOpenSession('s-5'))
    await page.locator('.msg.assistant', { hasText: 'answer s-5' }).waitFor()
    check(await work.count() === 0, 'notification deep link opens its conversation from a destination')
    await draft.fill('run the long thing')
    await page.locator('.composer').getByRole('button', { name: 'Send', exact: true }).click()
    await go('Work')
    await page.getByRole('button', { name: 'Review pending approval' }).click()
    const approval = page.getByRole('group', { name: 'Approval required' })
    await approval.getByRole('button', { name: 'Deny', exact: true }).click()
    await approval.waitFor({ state: 'detached' })
    check(true, 'a pending approval remains reachable after leaving the chat')
    await page.setViewportSize({ width: 1024, height: 760 })
    await go('Home')
    const box = await nav.boundingBox()
    const left = await page.locator('.drawer').boundingBox()
    check(box && left && box.x >= left.x + left.width - 1, 'on a tablet the main navigation sits beside the docked drawer')
  } finally {
    await page.close()
  }

  const ar = await browser.newPage({ viewport: { width: 320, height: 740 }, locale: 'ar-EG' })
  try {
    await ar.addInitScript(() => localStorage.setItem('hm.theme', 'light'))
    await ar.goto(WEB + '/')
    const nav = ar.getByRole('navigation', { name: 'التنقل الرئيسي' })
    await nav.getByRole('button', { name: 'الرئيسية', exact: true }).click()
    await ar.getByRole('status').waitFor()
    await ar.getByText('متصل', { exact: true }).waitFor()
    check(await nav.evaluate(el => getComputedStyle(el).direction === 'rtl' && [...el.querySelectorAll('button')].every(b => b.scrollWidth <= b.clientWidth)), 'localized navigation is RTL and fits at 320px')
    check(await ar.locator('html').getAttribute('data-theme') === 'light', 'Home follows the existing light theme')
    await ar.screenshot({ path: path.join(SHOTS, 'hermes-phase-01-home-ar-light.png') })
    await nav.getByRole('button', { name: 'العمل', exact: true }).click()
    await ar.screenshot({ path: path.join(SHOTS, 'hermes-phase-01-work-ar-light.png') })
  } finally {
    await ar.close()
  }
}
